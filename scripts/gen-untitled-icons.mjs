/**
 * Extract SVG path data from @untitledui/icons (React) into a Svelte-friendly registry.
 * Usage: node scripts/gen-untitled-icons.mjs
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const root = path.resolve(__dirname, '..')
const dist = path.join(root, 'node_modules', '@untitledui', 'icons', 'dist')
const outFile = path.join(root, 'src', 'lib', 'icons', 'registry.ts')

/** Icons used (or likely soon) in the Zarniwoop shell. Add names here, then re-run. */
const ICON_NAMES = [
  'AlignLeft01',
  'AlignRight01',
  'Browser',
  'ChevronLeft',
  'ChevronRight',
  'Globe01',
  'LayoutAlt01',
  'LayoutLeft',
  'LayoutRight',
  'MessageChatSquare',
  'Power01',
  'RefreshCw01',
  'Send01',
  'Settings01',
  'XClose'
]

function extractPaths(source) {
  const paths = []
  const re = /createElement\("path",\{d:"((?:\\.|[^"\\])*)"\}/g
  let match
  while ((match = re.exec(source)) !== null) {
    paths.push(match[1].replace(/\\"/g, '"'))
  }
  if (paths.length === 0) {
    throw new Error('No path elements found')
  }
  return paths
}

const entries = []
for (const name of ICON_NAMES) {
  const file = path.join(dist, `${name}.mjs`)
  if (!fs.existsSync(file)) {
    throw new Error(`Missing icon module: ${name} (${file})`)
  }
  const source = fs.readFileSync(file, 'utf8')
  const paths = extractPaths(source)
  const lit = paths.map((d) => `    ${JSON.stringify(d)}`).join(',\n')
  entries.push(`  ${name}: [\n${lit}\n  ]`)
}

const banner = `/* Generated by scripts/gen-untitled-icons.mjs - do not edit by hand.
 * Source: @untitledui/icons (Untitled UI Icons, line style).
 */
`

const body = `${banner}export const untitledIcons = {
${entries.join(',\n')}
} as const

export type UntitledIconName = keyof typeof untitledIcons
`

fs.mkdirSync(path.dirname(outFile), { recursive: true })
fs.writeFileSync(outFile, body, 'utf8')
console.log(`Wrote ${ICON_NAMES.length} icons → ${path.relative(root, outFile)}`)
